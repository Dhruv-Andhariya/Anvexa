'use client';

import { DSA_TOPIC_PREFIX, ROUNDS_LIMITS, dsaBankEntry, dsaBankIdOf, type Difficulty, type SqlBankListItem } from '@hireflow/contracts';
import { useEffect, useRef, useState } from 'react';
import { ApiError } from '@/lib/api';
import { fromAuthored, fromGenerated, newCodingDraft, newQuestion, type QuestionDraft, type RoundDraft } from '@/lib/rounds';
import { generateCodingProblems, generateQuestions } from '@/lib/rounds-api';
import { activeSqlQuestions, getSqlQuestion } from '@/lib/sql-bank-api';
import { Button, Spinner, inputClass } from '../ui';

const DIFFICULTIES: Difficulty[] = ['EASY', 'MEDIUM', 'HARD'];
const label = (d: Difficulty) => d[0] + d.slice(1).toLowerCase();

/** HR's settings for a question of the plan that is not in the round yet. */
interface Plan {
  difficulty: Difficulty;
  topics: string;
  marks: string;
}

const wholeMarks = (s: string): number | null => {
  const n = Number(s);
  return s.trim() && Number.isInteger(n) && n >= 1 && n <= ROUNDS_LIMITS.marksMax ? n : null;
};

/** A short name for a problem of the round: its title, else the start of its text. */
export function problemName(q: QuestionDraft): string {
  const bankId = dsaBankIdOf(q.topics);
  const name = q.coding?.title || q.sql?.title || (bankId ? dsaBankEntry(bankId)?.title : '') || q.text.trim().split('\n')[0] || '';
  return name.length > 60 ? `${name.slice(0, 57)}…` : name || 'Untitled problem';
}

/**
 * DSA coding / SQL round: one section per planned question ("Number of questions"). An added question shows its marks
 * and difficulty (editable); a question not added yet has its own difficulty, topics and marks, and is generated by the
 * AI (DSA: one problem checked on the code runner), picked from the SQL question bank (SQL: graded online), or started
 * as HR's own question. Nothing is saved until HR saves the round.
 */
export function CodingPlan({
  jobId,
  variant,
  round,
  target,
  marksEach,
  disabled,
  onChange,
}: {
  jobId: string;
  variant: 'dsa' | 'sql';
  round: RoundDraft;
  /** HR's planned number of questions (null = not set). */
  target: number | null;
  marksEach: number | null;
  disabled: boolean;
  onChange: (r: RoundDraft) => void;
}) {
  // the AI answers after a while: add its problem to the round as it is THEN (HR may have edited meanwhile)
  const latest = useRef(round);
  useEffect(() => {
    latest.current = round;
  }, [round]);

  const missing = Math.max(0, (target ?? 0) - round.questions.length);
  const [plans, setPlans] = useState<Plan[]>([]);
  const planAt = (i: number): Plan => plans[i] ?? { difficulty: 'MEDIUM', topics: '', marks: marksEach ? String(marksEach) : '' };
  const setPlan = (i: number, patch: Partial<Plan>) =>
    setPlans(Array.from({ length: Math.max(plans.length, i + 1) }, (_, k) => (k === i ? { ...planAt(k), ...patch } : planAt(k))));
  const dropPlan = (i: number) => setPlans(Array.from({ length: missing }, (_, k) => planAt(k)).filter((_, k) => k !== i));

  const [busy, setBusy] = useState<number | null>(null);
  const [errors, setErrors] = useState<Record<number, string>>({});
  const sql = variant === 'sql';
  // SQL: the company's active SQL bank questions (the ones graded online), loaded once
  const [sqlBank, setSqlBank] = useState<SqlBankListItem[] | null>(null);
  useEffect(() => {
    if (!sql) return;
    let live = true;
    activeSqlQuestions().then(
      (list) => live && setSqlBank(list),
      () => live && setSqlBank([]),
    );
    return () => {
      live = false;
    };
  }, [sql]);
  const fail = (i: number, err: unknown) =>
    setErrors((e) => ({ ...e, [i]: err instanceof ApiError ? err.message : 'Something went wrong. Please try again.' }));
  /** A new question took the place of section i: the sections below move up, so their old messages are cleared. */
  const filled = (i: number, q: QuestionDraft) => {
    addQuestion(q);
    dropPlan(i);
    setErrors({});
  };
  const topicsOf = (plan: Plan) =>
    plan.topics
      .split(',')
      .map((t) => t.trim())
      .filter(Boolean)
      .slice(0, 10);

  /** SQL: a copy of a bank question (its tables and datasets grade the answer online); HR's marks win over the bank's. */
  const pickSql = async (i: number, id: string) => {
    const plan = planAt(i);
    setBusy(i);
    setErrors({ ...errors, [i]: '' });
    try {
      const b = await getSqlQuestion(id);
      const marks = wholeMarks(plan.marks);
      filled(i, {
        ...newQuestion('CODING'),
        sql: b.problem,
        topics: b.topics.filter((t) => !t.startsWith(DSA_TOPIC_PREFIX)).slice(0, ROUNDS_LIMITS.topicsMax),
        text: b.description,
        marks: String(marks ?? b.marks),
        difficulty: b.difficulty,
        language: 'SQL',
      });
    } catch (err) {
      fail(i, err);
    } finally {
      setBusy(null);
    }
  };

  /** SQL: one question written by the AI (HR checks the answers: only bank questions are graded online). */
  const generateSql = async (i: number) => {
    const plan = planAt(i);
    setBusy(i);
    setErrors({ ...errors, [i]: '' });
    try {
      const res = await generateQuestions(jobId, {
        roundType: 'SQL',
        roundName: latest.current.name.trim() || 'SQL',
        roundDescription: latest.current.description,
        count: 1,
        difficulty: plan.difficulty,
        topics: topicsOf(plan).slice(0, ROUNDS_LIMITS.topicsMax),
        kinds: ['CODING'],
        avoid: latest.current.questions.map((q) => q.text).filter(Boolean),
      });
      const g = res.questions[0];
      if (!g) {
        setErrors((e) => ({ ...e, [i]: 'The AI did not write a usable question this time. Please try again.' }));
        return;
      }
      const marks = wholeMarks(plan.marks);
      filled(i, { ...fromGenerated(g), ...(marks ? { marks: String(marks) } : {}), difficulty: plan.difficulty, language: 'SQL' });
    } catch (err) {
      fail(i, err);
    } finally {
      setBusy(null);
    }
  };

  const setQuestion = (j: number, patch: Partial<QuestionDraft>) =>
    // "Marks per question" then shows the common value only while every question has the same marks
    onChange({ ...round, marksEach: undefined, questions: round.questions.map((q, k) => (k === j ? { ...q, ...patch } : q)) });

  const addQuestion = (q: QuestionDraft) =>
    onChange({ ...latest.current, marksEach: undefined, questions: [...latest.current.questions, q].slice(0, ROUNDS_LIMITS.questionsMax) });

  const generate = async (i: number) => {
    const plan = planAt(i);
    setBusy(i);
    setErrors({ ...errors, [i]: '' });
    try {
      const res = await generateCodingProblems(jobId, {
        count: 1,
        difficulty: plan.difficulty,
        topics: topicsOf(plan),
        avoid: latest.current.questions.map((q) => q.coding?.title || q.text).filter(Boolean).slice(0, 100),
      });
      const p = res.problems[0];
      if (!p) {
        setErrors((e) => ({ ...e, [i]: res.dropped[0]?.reason ?? 'The AI did not write a usable problem this time. Please try again.' }));
        return;
      }
      const marks = wholeMarks(plan.marks);
      filled(i, { ...fromAuthored(p), ...(marks ? { marks: String(marks) } : {}), difficulty: plan.difficulty });
    } catch (err) {
      fail(i, err);
    } finally {
      setBusy(null);
    }
  };

  const writeOwn = (i: number) => {
    const plan = planAt(i);
    const marks = wholeMarks(plan.marks);
    filled(i, {
      ...newQuestion('CODING'),
      // DSA: HR's own problem with test cases; SQL: HR's own question (HR checks the answer)
      ...(sql ? { language: 'SQL' } : { coding: newCodingDraft() }),
      difficulty: plan.difficulty,
      ...(marks ? { marks: String(marks) } : {}),
    });
  };

  if (!round.questions.length && !missing) return null;

  return (
    <div className="flex flex-col gap-2 border-t border-border pt-3 sm:col-span-2">
      {round.questions.map((q, j) => (
        <div key={q.key} className="flex flex-wrap items-center gap-x-4 gap-y-2 rounded-md border border-border bg-surface p-2 text-sm">
          <span className="min-w-0 flex-1 truncate" title={problemName(q)}>
            <span className="font-semibold">Question {j + 1}</span> <span className="text-muted">· {problemName(q)}</span>
          </span>
          <label className="flex items-center gap-2">
            Marks
            <input
              type="number"
              min={1}
              max={ROUNDS_LIMITS.marksMax}
              aria-label={`Marks of question ${j + 1}`}
              className={`${inputClass} w-20 py-1`}
              value={q.marks}
              disabled={disabled}
              onChange={(e) => setQuestion(j, { marks: e.target.value })}
            />
          </label>
          <label className="flex items-center gap-2">
            Difficulty
            <select
              aria-label={`Difficulty of question ${j + 1}`}
              className={`${inputClass} w-28 py-1`}
              value={q.difficulty ?? ''}
              disabled={disabled}
              onChange={(e) => setQuestion(j, { difficulty: (e.target.value || null) as Difficulty | null })}
            >
              <option value="">—</option>
              {DIFFICULTIES.map((d) => (
                <option key={d} value={d}>
                  {label(d)}
                </option>
              ))}
            </select>
          </label>
        </div>
      ))}

      {Array.from({ length: missing }, (_, i) => {
        const plan = planAt(i);
        const n = round.questions.length + i + 1;
        const marksBad = !!plan.marks.trim() && !wholeMarks(plan.marks);
        return (
          <div key={`plan-${i}`} className="flex flex-col gap-2 rounded-md border border-dashed border-accent/50 bg-accent-soft/30 p-2">
            <div className="flex flex-wrap items-end gap-3">
              <span className="self-center text-sm font-semibold">
                Question {n} <span className="text-xs font-normal text-muted">(not added yet)</span>
              </span>
              <label className="flex flex-col gap-1 text-xs font-medium">
                Difficulty
                <select
                  aria-label={`Difficulty of question ${n}`}
                  className={`${inputClass} w-28 py-1`}
                  value={plan.difficulty}
                  disabled={disabled || busy !== null}
                  onChange={(e) => setPlan(i, { difficulty: e.target.value as Difficulty })}
                >
                  {DIFFICULTIES.map((d) => (
                    <option key={d} value={d}>
                      {label(d)}
                    </option>
                  ))}
                </select>
              </label>
              <label className="flex min-w-44 flex-1 flex-col gap-1 text-xs font-medium">
                Topics (optional, comma separated)
                <input
                  aria-label={`Topics of question ${n}`}
                  className={`${inputClass} py-1`}
                  placeholder="e.g. arrays, hashing"
                  value={plan.topics}
                  maxLength={600}
                  disabled={disabled || busy !== null}
                  onChange={(e) => setPlan(i, { topics: e.target.value })}
                />
              </label>
              <label className="flex flex-col gap-1 text-xs font-medium">
                Marks
                <input
                  type="number"
                  min={1}
                  max={ROUNDS_LIMITS.marksMax}
                  aria-label={`Marks of question ${n}`}
                  placeholder="AI's"
                  className={`${inputClass} w-20 py-1`}
                  value={plan.marks}
                  aria-invalid={marksBad}
                  disabled={disabled || busy !== null}
                  onChange={(e) => setPlan(i, { marks: e.target.value })}
                />
              </label>
            </div>
            <div className="flex flex-wrap items-center gap-2">
              {sql && (
                <select
                  aria-label={`Pick question ${n} from the SQL question bank`}
                  className={`${inputClass} w-auto max-w-xs py-1`}
                  value=""
                  disabled={disabled || busy !== null || marksBad || !sqlBank?.length}
                  onChange={(e) => e.target.value && void pickSql(i, e.target.value)}
                >
                  <option value="">
                    {sqlBank === null ? 'Loading SQL question bank…' : sqlBank.length ? '📋 Pick from SQL question bank…' : 'No active SQL questions (SQL questions page)'}
                  </option>
                  {(sqlBank ?? [])
                    .filter((b) => !latest.current.questions.some((q) => q.sql?.bankId === b.id))
                    .map((b) => (
                      <option key={b.id} value={b.id}>
                        {b.title} ({label(b.difficulty)}, {b.marks} marks)
                      </option>
                    ))}
                </select>
              )}
              <Button variant={sql ? 'secondary' : 'primary'} className="py-1" onClick={() => void (sql ? generateSql(i) : generate(i))} disabled={disabled || busy !== null || marksBad}>
                {busy === i && <Spinner />} ✨ Generate question {n} with AI
              </Button>
              <Button className="py-1" onClick={() => writeOwn(i)} disabled={disabled || busy !== null || marksBad}>
                ✎ Write my own
              </Button>
              {busy === i && (
                <span className="text-xs text-muted">{sql ? 'Working…' : 'Writing the problem and checking its tests on the code runner… (up to a minute)'}</span>
              )}
              {marksBad && <span className="text-xs text-danger">Marks: a whole number from 1 to {ROUNDS_LIMITS.marksMax}, or leave empty.</span>}
              {errors[i] && (
                <span role="alert" className="text-xs text-danger">
                  {errors[i]}
                </span>
              )}
            </div>
          </div>
        );
      })}
    </div>
  );
}
