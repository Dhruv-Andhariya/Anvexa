"""Pydantic models of the AAIE worker (Phase 1: no AI fields).

JSON uses camelCase (like the TypeScript contracts the API sends); Python uses snake_case. Unknown fields are refused,
so a typo or an unexpected field never passes silently. These models only describe evidence the existing execution
engines already produced (Piston for DSA, the SQLite sandbox for SQL); nothing here runs or changes code.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field, model_validator
from pydantic.alias_generators import to_camel


class _Model(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True, extra="forbid", frozen=True)


class CaseStatus(StrEnum):
    """Status of one test case, as the existing evaluator reports it."""

    PASSED = "passed"
    WRONG_ANSWER = "wrong_answer"
    RUNTIME_ERROR = "runtime_error"
    TIME_LIMIT = "time_limit"
    COMPILE_ERROR = "compile_error"
    INTERNAL_ERROR = "internal_error"


class Verdict(StrEnum):
    PASSED = "passed"
    FAILED = "failed"
    COMPILE_ERROR = "compile_error"
    INTERNAL_ERROR = "internal_error"


class SubmissionKind(StrEnum):
    RUN = "RUN"
    SUBMIT = "SUBMIT"


class Engine(StrEnum):
    PISTON = "PISTON"
    SQLITE = "SQLITE"


class Language(StrEnum):
    PYTHON = "python"
    JAVA = "java"
    CPP = "cpp"
    SQL = "sql"


class CaptureKeySource(StrEnum):
    CLIENT = "CLIENT"  # one key per click, generated by the candidate page (D35)
    SERVER = "SERVER"  # older page without a key


class CaseCategory(StrEnum):
    """Test-case categories (D25). Explanation only - they never change the marks formula."""

    NORMAL = "normal"
    BOUNDARY = "boundary"
    EDGE = "edge"
    DUPLICATE_VALUES = "duplicate_values"
    NULL_VALUES = "null_values"
    EMPTY_INPUT = "empty_input"
    LARGE_INPUT = "large_input"


class ErrorClass(StrEnum):
    """Who a failure belongs to. Shape only in Step 1; the classifier is Step 2."""

    NONE = "NONE"
    CANDIDATE = "CANDIDATE"
    INFRASTRUCTURE = "INFRASTRUCTURE"


class RunnerStatus(StrEnum):
    """Piston's own status for one execution stage (trusted metadata; never candidate output)."""

    RUNTIME_ERROR = "RE"  # non-zero exit
    SIGNAL = "SG"  # killed by a signal
    TIMEOUT = "TO"  # a wall-clock or CPU limit was hit
    STDOUT_LIMIT = "OL"  # too much output
    STDERR_LIMIT = "EL"
    INTERNAL_ERROR = "XX"  # the runner itself failed


class HealthResponse(_Model):
    status: str = "ok"
    service: str
    version: str
    #: Phase 1: always false - the worker makes no AI calls.
    ai_enabled: bool = False


class CaseResult(_Model):
    """One test case's outcome. Statuses and timings only: never hidden inputs or expected outputs."""

    case_id: str = Field(min_length=1, max_length=100)
    hidden: bool
    category: CaseCategory | None = None
    status: CaseStatus
    #: CPU time the program used (Piston `cpu_time`), ms.
    time_ms: int | None = Field(default=None, ge=0)
    memory_kb: int | None = Field(default=None, ge=0)
    # Trusted execution metadata (from the runner / the API's evaluator, never from the candidate or the AI). Optional;
    # used by the AAIE worker to tell candidate failures from infrastructure failures (H6).
    #: Wall-clock time of the run (Piston `wall_time`), ms.
    wall_time_ms: int | None = Field(default=None, ge=0)
    exit_code: int | None = Field(default=None, ge=0, le=255)
    #: The signal that ended the run, e.g. "SIGSEGV", "SIGKILL".
    signal: str | None = Field(default=None, pattern=r"^SIG[A-Z0-9]{2,10}$")
    runner_status: RunnerStatus | None = None
    #: The interpreter / runtime reported an exception whose trace points into the candidate's own lines.
    exception_in_candidate_code: bool | None = None


class SubmissionEvidence(_Model):
    """One captured Run or Submit with its execution result (D24, D35, D36)."""

    kind: SubmissionKind
    capture_key: str = Field(pattern=r"^[A-Za-z0-9_-]{8,64}$")
    capture_key_source: CaptureKeySource
    language: Language
    engine: Engine
    #: SHA-256 of the submitted code / query, lower-case hex.
    code_hash: str = Field(pattern=r"^[0-9a-f]{64}$")
    verdict: Verdict
    passed: int = Field(ge=0)
    total: int = Field(ge=0)
    #: A result was returned (refused requests are never captured).
    evaluation_completed: bool
    #: The original progress (codingState) was saved; always false for a Run.
    progress_persisted: bool
    cases: list[CaseResult] = Field(default_factory=list, max_length=500)

    @model_validator(mode="after")
    def _consistent(self) -> SubmissionEvidence:
        if self.passed > self.total:
            raise ValueError("passed cannot be more than total")
        if (self.language is Language.SQL) != (self.engine is Engine.SQLITE):
            raise ValueError("SQL queries run on the SQLite sandbox and programs on Piston")
        if self.kind is SubmissionKind.RUN and self.progress_persisted:
            raise ValueError("a Run never saves progress")
        if self.cases:
            if len(self.cases) != self.total:
                raise ValueError("total must equal the number of cases")
            if sum(c.status is CaseStatus.PASSED for c in self.cases) != self.passed:
                raise ValueError("passed must equal the number of passed cases")
            if len({c.case_id for c in self.cases}) != len(self.cases):
                raise ValueError("case ids must be unique")
        return self
